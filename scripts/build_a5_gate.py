# -*- coding: utf-8 -*-
"""Build the A5 gate kernel's payload: the extracted model code, inlined, plus the gate logic.

WHY A BUILDER.  A Kaggle *script* kernel uploads exactly ONE `code_file`, so shipping `gate.py` and
`a5_model.py` side by side does not work -- the first push died with `ModuleNotFoundError: No module
named 'a5_model'`.  (The repo has met this shape before: a payload that is present locally and
absent in the run.)  So the model body is inlined into one generated file, while `a5_model.py`
stays the versioned source of truth that `scripts/extract_a5_model.py --check` re-verifies against
the notebook.

WHAT IT ADDS TO THE VERBATIM BODY, AND NOTHING ELSE
    * `import torch`, `torch.nn as nn`, `torch.nn.functional as F` -- the notebook cell relied on
      earlier cells for these, so a standalone module must bring its own;
    * the gate logic from `gate.py`, with its `from a5_model import ...` line removed because the
      names are now in the same namespace.

Usage:
    python scripts/build_a5_gate.py            # write kernels/kernel-a5port/kernel_main.py
    python scripts/build_a5_gate.py --check     # assert the payload matches its two sources
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
ROOT = pathlib.Path(__file__).resolve().parent.parent
KDIR = ROOT / "kernels" / "kernel-a5port"
MODEL = KDIR / "a5_model.py"
GATE = KDIR / "gate.py"
OUT = KDIR / "kernel_main.py"

IMPORTS = ("import torch\nimport torch.nn as nn\nimport torch.nn.functional as F  "
           "# noqa: F401  (the cell used F; A5's path may not)\n")

# ⚠️ Both of these are LINE patterns, and both must match exactly once.  The first version used
# `if line not in text` followed by `text.replace(line + "\n", "")`: the *check* passed (the import
# line contains the probe as a substring) while the *replacement* did nothing, because the real line
# carries a trailing comment.  The payload then shipped with the import still in it and died again
# with the same ModuleNotFoundError -- a check that does not look at what it edits.  Anchored regexes
# plus asserting the result is gone.
DROP = (r"^from a5_model import[^\n]*\n",
        r"^sys\.path\.insert\(0, os\.path\.dirname\(os\.path\.abspath\(__file__\)\)\)[^\n]*\n")


def model_body():
    text = MODEL.read_text(encoding="utf-8")
    i = text.index('"""', text.index('"""') + 3) + 3          # end of the module docstring
    return text[i:].strip("\n")


def gate_body():
    import re
    text = GATE.read_text(encoding="utf-8")
    for pat in DROP:
        text, n = re.subn(pat, "", text, flags=re.M)
        if n != 1:
            raise SystemExit("!! %r matched %d lines in gate.py -- refusing to build" % (pat, n))
    if "from a5_model import" in text:
        raise SystemExit("!! the a5_model import survived the strip")
    return text


def payload():
    return ("# GENERATED by scripts/build_a5_gate.py -- do not edit; edit a5_model.py / gate.py\n"
            + IMPORTS + "\n\n# ---- verbatim from kernel-0943 cell 39 (see a5_model.py header) ----\n"
            + model_body() + "\n\n# ---- the gate ----\n" + gate_body())


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = payload()

    probes = ["class Net", "N_SLOT_TYPES", "load_state_dict(z[\"state_dict\"], strict=True)",
              "def build(", "patch_embed"]
    for p in probes:
        if p not in text:
            raise SystemExit("!! payload is missing %r" % p)
    if "from a5_model import" in text:
        raise SystemExit("!! payload still imports a5_model -- a script kernel uploads ONE file")

    if a.check:
        if not OUT.is_file():
            raise SystemExit("!! %s missing -- run without --check" % OUT)
        if OUT.read_text(encoding="utf-8") != text:
            raise SystemExit("!! kernel_main.py is stale: rerun scripts/build_a5_gate.py")
        print("CHECK OK: kernel_main.py matches a5_model.py + gate.py")
        return 0

    KDIR.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    meta_p = KDIR / "kernel-metadata.json"
    meta = json.loads(meta_p.read_text(encoding="utf-8"))
    if meta.get("code_file") != OUT.name:
        meta["code_file"] = OUT.name
        meta_p.write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote %s (%d chars); code_file=%s" % (OUT, len(text), meta["code_file"]))
    print("  model body : %d chars from a5_model.py" % len(model_body()))
    print("  gate logic : %d chars from gate.py" % len(gate_body()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
