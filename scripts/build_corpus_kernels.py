# -*- coding: utf-8 -*-
"""Fan the corpus builder out into N concurrent CPU shard kernels.

WHY SHARDS: the full 64-slot corpus is 31.9 GB, over Kaggle's 20 GB kernel-output limit, so it has
to be split anyway -- and splitting it across CONCURRENT kernels is also the only real speed-up
available.  Measured on the first (single-threaded, per-candidate header-reading) version: >40 min
for 8 studies.  Three fixes are in `build_corpus.py` v2 (one series scan per group, `specific_tags`,
multiprocessing); running 4 shards at once multiplies that again.

CPU kernels consume no GPU and no TPU quota (FACTS A6), and `kaggle quota` has no CPU line at all,
so this work is free -- it only competes with wall-clock.

Each shard kernel gets the SAME script file plus a 5-line environment prelude, so there is exactly
one copy of the builder logic in the repo (nothing to drift).

    python scripts/build_corpus_kernels.py --shards 4 --total 4407 --count 1100
    python scripts/build_corpus_kernels.py --shards 4 --total 4407 --count 1100 --push
"""
import argparse
import json
import pathlib
import shutil
import subprocess
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
ROOT = pathlib.Path(__file__).resolve().parent.parent
from kpaths import kdir          # kernels/ layout, see kpaths.py
SRC = kdir("kernel-corpus64")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--shards", type=int, default=4)
    ap.add_argument("--total", type=int, default=4407)
    ap.add_argument("--count", type=int, default=1100)
    ap.add_argument("--threads", type=int, default=4)
    ap.add_argument("--push", action="store_true")
    a = ap.parse_args()

    src_code = (SRC / "build_corpus.py").read_text(encoding="utf-8")
    base_meta = json.loads((SRC / "kernel-metadata.json").read_text(encoding="utf-8"))

    built = []
    for i in range(a.shards):
        start = i * a.count
        if start >= a.total:
            break
        count = min(a.count, a.total - start)
        name = "kernel-corpus64-s%d" % i
        dst = kdir(name)
        dst.mkdir(exist_ok=True)
        prelude = (
            "# ==== shard prelude (generated by scripts/build_corpus_kernels.py) ====\n"
            "# A Kaggle script kernel gets no argv, so the shard parameters ride in the environment.\n"
            "import os as _os\n"
            "_os.environ.setdefault('CORPUS_MODE', 'build64')\n"
            "_os.environ.setdefault('CORPUS_START', '%d')\n"
            "_os.environ.setdefault('CORPUS_COUNT', '%d')\n"
            "_os.environ.setdefault('CORPUS_SHARD', 's%d')\n"
            "_os.environ.setdefault('CORPUS_THREADS', '%d')\n"
            "# ==== end shard prelude ====\n"
        ) % (start, count, i, a.threads)
        (dst / "build_corpus.py").write_text(prelude + src_code, encoding="utf-8")

        meta = dict(base_meta)
        meta["id"] = "ppxl16/rsna-knee-corpus64-s%d" % i
        meta["title"] = "RSNA knee corpus64 s%d" % i
        meta["is_private"] = True
        (dst / "kernel-metadata.json").write_text(
            json.dumps(meta, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        built.append((name, meta["id"], start, count))
        print("built %-22s id=%-34s studies %4d..%-4d (n=%d)" % (
            name, meta["id"], start, start + count - 1, count))

    # local syntax check on every generated shard -- never push code that has not been parsed
    for name, _id, _s, _c in built:
        p = kdir(name) / "build_corpus.py"
        try:
            compile(p.read_text(encoding="utf-8"), str(p), "exec")
        except SyntaxError as e:
            raise SystemExit("!! shard %s does not parse: %s" % (name, e))
    print("all %d shards parse" % len(built))

    if a.push:
        print()
        for name, kid, _s, _c in built:
            out = subprocess.run(["kaggle", "kernels", "push", "-p", str(kdir(name))],
                                 capture_output=True, text=True)
            blob = (out.stdout or "") + (out.stderr or "")
            ok = "successfully pushed" in blob
            print("%-22s %s" % (name, "PUSH OK" if ok else "PUSH FAILED"))
            if not ok:
                print(blob.strip()[:400])
    else:
        print("\n(push with --push; each shard is an independent CPU kernel and they run CONCURRENTLY)")


if __name__ == "__main__":
    main()
