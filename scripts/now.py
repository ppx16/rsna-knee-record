    L.append("```")
    L.append(r"RSNAKneeDirector  每 180 分钟 : download / submit / score（scripts\director.cmd）")
    L.append(r"RSNAKneeQueue     每 180 分钟 : 把空闲 GPU 槽补满（scripts\queue.cmd，日志 state\queue_task.log）")
    L.append("```")
    L.append("⚠️ 两条政策（用户 2026-09-24）：**GPU 只用来提交算成绩，实验一律走 TPU**；"
             "TPU 排队期间【坑位】也要一直填着（A28/A33）。")
    L.append("手工补做（开机后想立刻推进时）：")
    L.append("```")
    L.append(r"python scripts\director.py --once      # 交掉到期的提交、收分、记名次")
    L.append(r"python scripts\status.py               # 榜面 + 该选哪两个最终提交")
    L.append(r"python scripts\cv_queue.py --once      # 把空闲 GPU 槽补满（幂等，不会因 GPU 上限而死）")
    L.append(r"python scripts\lb_ledger.py            # 用比赛 API 重生成 LB 真值账本（否则它会悄悄过期）")
    L.append(r"python scripts\now.py                  # 刷新本文件")
    L.append("```")
    L.append("")
    L.append("## ⚠️ Kaggle 凭据（2026-09-14 轮换过，**出 401 先看这里**）")
    L.append("```")
    L.append("机制 : KGAT_... 形式的新 token **不能**放进 ~/.kaggle/kaggle.json 的 key 字段")
    L.append("       （实测：2.1.2 回 401、2.2.4 直接要求重新认证）——而且**读路径与写路径要放两处**：")
    L.append("         读（list/status/submissions） : 环境变量 KAGGLE_API_TOKEN")
    L.append("         写（kernels push）            : **文件** ~/.kaggle/access_token")
    L.append("       两处都已配好；环境变量设在 **User 级**（重启后的新 shell / 计划任务自动继承）。")
    L.append("本会话注意 : 本进程继承的是旧环境，所以在本会话里跑脚本前要显式带上：")
    L.append(r"       $env:KAGGLE_API_TOKEN = [Environment]::GetEnvironmentVariable('KAGGLE_API_TOKEN','User')")
    L.append("")
    L.append("排查 : `401 Unauthorized` ⇒ 环境变量；")
    L.append("       `Save the token to ~/.kaggle/access_token` ⇒ 那个文件（写路径）；")
    L.append("       `400 … CreateCodeSubmission body=None` ⇒ **先查是不是少了 `-f submission.csv`**。")
    L.append("       ⚠️ 这条旧记录原本写的是「⇒ 当天提交配额用尽」，**那是错的**：2026-09-27 实测在")
    L.append("       `Remaining today: 1` 时仍然 400，补上 `-f submission.csv` 立刻成功（`56613303`）。")
    L.append("       ⇒ 配额用尽的判据是 `submission-limits` 报 `Remaining today: 0`，**不是**这个 400。")
    L.append("```")
    L.append("")
    L.append("## ⚠️ 读导演输出时的两个坑（2026-09-14 都踩过）")
    L.append("```")
    L.append("1) `director.py --once --dry-run` 可能只打一行 `another director pass is active` 就退出")
    L.append("   （计划任务的导演正持有锁）。**那一行 ≠ 队列是空的** —— 等一轮或看状态文件。")
