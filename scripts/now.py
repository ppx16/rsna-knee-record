"""Generate state/NOW.md -- the one-page brief to read at the start of every round.

WHY THIS EXISTS (user report, 2026-09-14)
    "感觉你的上下文是不是有问题，经常忘记之前做过的事" -- correct, and the cause is structural:
    the session gets compacted, so anything that is not in a FILE is gone next round.  The
    remedy is not "try harder to remember", it is to make the entry point two short files:

        state/NOW.md    GENERATED by this script -- can never go stale, never hand-edited
        state/FACTS.md  the append-only ledger of settled facts and killed directions

    HANDOFF.md stays the narrative/archive (it is ~7400 lines; reading it every round is what
    burned the context in the first place).

RULES THIS FOLLOWS
    HANDOFF 52.3: state may only be read by the program that owns its schema.  So this script
    never parses state/*.json by hand -- it SHELLS OUT to the sanctioned readouts
    (status.py, cv_queue.py) and otherwise reports file facts (mtimes, sizes).

Usage:
    python scripts/now.py            # full: includes the leaderboard readout (~30 s, network)
    python scripts/now.py --fast     # local only, no network
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "state", "NOW.md")
PY = sys.executable


def run(args, timeout=600):
    try:
        p = subprocess.run(args, capture_output=True, text=True, timeout=timeout, cwd=ROOT)
        return ((p.stdout or "") + (p.stderr or "")).strip()
    except subprocess.TimeoutExpired:
        return "(timed out)"
    except Exception as e:                                            # pragma: no cover
        return "(failed: %s)" % e


def tail(path, n):
    p = os.path.join(ROOT, path)
    if not os.path.exists(p):
        return ["(missing) %s" % path]
    with open(p, encoding="utf-8", errors="replace") as fh:
        return fh.read().splitlines()[-n:]


