"""Generate docs/INDEX.md from what is actually in docs/.

Why: ninety-odd documents accumulated over three weeks, most of them from eras that no longer apply. A
reader -- or a future session -- cannot tell `FIND-2026-10-04-private-datasets-946.md` from a live
instruction without opening it. The index classifies every file by the era its name carries and marks the
handful that are still authoritative, so nobody has to guess.

Regenerate with: python work/make_docs_index.py
"""
import re
import sys
from datetime import datetime
from pathlib import Path

sys.stdout.reconfigure(encoding='utf-8', errors='replace')
ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'docs'
OUT = DOCS / 'INDEX.md'

# files that still carry authority. Anything not listed is history by construction.
LIVE = {
    'DEADLINE-CHECKLIST.md': 'The five-minute deadline procedure and the do-not list.',
    'FINAL-TICK.md': 'Which two submissions to tick, and how to recognise them in the UI.',
    'LESSONS.md': 'The five falsified predictions, six blind instruments, four rules.',
}
LIVE_PREFIX = ('HANDOVER-',)

KIND = {
    'FIND-': 'a finding: something measured, with the number',
    'RESULT-': 'the outcome of a registered experiment',
    'PREREG-': 'a pre-registration: prediction written before the measurement',
    'PLAN-': 'a plan (most were superseded)',
    'STATUS-': 'state of the campaign on that day',
    'STRATEGY-': 'a strategic note',
    'SWEEP-': 'a sweep over the public surface',
    'SPEC-': 'a technical specification',
    'PREDICT-': 'a forecast, kept so it can be scored',
    'DECISION-': 'a decision and its reasons',
    'REVIEW-': 'a review of a session',
    'AUDIT-': 'an audit of provenance or correctness',
    'CHECK-': 'a check on a specific claim',
    'VERIFY-': 'a verification of a component',
    'REAUDIT-': 'a second audit',
    'ASSESS-': 'an assessment of whether something is reachable',
    'DECLINE-': 'levers examined and declined, with reasons',
    'READ-': 'a read-through of someone else\'s artifact',
    'TARGET-': 'a target statement',
    'EXTRACT-': 'source extracted for reuse',
    'DEPLOY-': 'deployment notes for a long run',
    'EFFICIENCY-': 'inference cost and runtime analysis',
    'INTEL-': 'competitive intelligence',
    'REVISION-': 'a revision of an earlier decision',
    'RUNBOOK-': 'a copy-pasteable procedure',
    'MIGRATION': 'the layout migration',
    'HANDOFF': 'the long narrative (superseded by the dated handovers)',
    'FINAL-SELECTION': 'a selection document from an older era',
    'PLAN-arm-image-metadata': 'a plan marked NOT RECOMMENDED, kept for its method',
}


def era(name: str, mtime: float) -> str:
    m = re.search(r'(\d{4}-\d{2}-\d{2})', name)
    day = m.group(1) if m else datetime.fromtimestamp(mtime).strftime('%Y-%m-%d')
    if day >= '2026-10-15':
        return 'E. the 0.958 endgame (2026-10-15 onward)'
    if day >= '2026-10-11':
        return 'D. the 0.954 to 0.957 climb (2026-10-11 .. 10-14)'
    if day >= '2026-10-06':
        return 'C. the 0.943 to 0.950 frontier (2026-10-06 .. 10-10)'
    if day >= '2026-10-01':
        return 'B. the first week of runs (2026-10-01 .. 10-05)'
    return 'A. setup and early reviews (2026-09)'


def tag(name: str) -> str:
    if name in LIVE or name.startswith(LIVE_PREFIX):
        return '**LIVE**'
    return 'history'


def main() -> int:
    files = sorted(p for p in DOCS.glob('*.md') if p.name != 'INDEX.md')
    groups: dict[str, list[Path]] = {}
    for p in files:
        groups.setdefault(era(p.name, p.stat().st_mtime), []).append(p)

    lines = [
        '# docs/ index',
        '',
        'Generated by `work/make_docs_index.py`; re-run it rather than editing this file.',
        '',
        'Three documents are authoritative. Everything else is a record of something that was true on a',
        'particular day, and several of them describe plans that were later falsified — that is what they are',
        'for. **Do not follow an instruction from a file tagged history.**',
        '',
        '## Live',
        '',
        '| file | what it is |',
        '|---|---|',
    ]
    for name, what in LIVE.items():
        lines.append('| [`%s`](%s) | %s |' % (name, name, what))
    handovers = sorted(p.name for p in files if p.name.startswith(LIVE_PREFIX))
    if handovers:
        lines.append('| `%s` | the current narrative handover |' % handovers[-1])

    lines += ['', '## By era', '']
    for key in sorted(groups, reverse=True):
        lines += ['### %s' % key, '', '| file | kb | what it is |', '|---|---|---|']
        for p in sorted(groups[key], key=lambda q: q.name):
            what = '—'
            for pref, desc in sorted(KIND.items(), key=lambda kv: -len(kv[0])):
                if p.name.startswith(pref):
                    what = desc
                    break
            lines.append('| [`%s`](%s) | %.0f | %s (%s) |'
                         % (p.name, p.name, p.stat().st_size / 1024, what, tag(p.name)))
        lines.append('')

    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('wrote %s with %d documents in %d eras' % (OUT, len(files), len(groups)))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
